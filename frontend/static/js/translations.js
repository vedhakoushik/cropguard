function applyTranslations(lang) {
  const trans = TRANSLATIONS[lang] || TRANSLATIONS.English;
  
  // Update all elements with data-i18n attribute
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    el.textContent = trans[key] || key;
  });

  // Update UI elements by ID
  const uiMap = {
    "newChatText": "newChatText",
    "recentAnalysesLabel": "recentAnalysesLabel",
    "langLabel": "langLabel",
    "expertSupportText": "expertSupportBtn",
    "clearAllBtn": "clearAllBtn",
    "topbarCtx": "selectCropAndDistrict",
    "analysisDashboardTitle": "analysisDashboardTitle",
    "panelEmptyText": "panelEmptyText",
    "locationHintText": "selectCropAndDistrict",
    "analysisDashboardTitle": "analysisDashboardTitle",
  };

  for (const [elementId, transKey] of Object.entries(uiMap)) {
    const element = document.getElementById(elementId);
    if (element) element.textContent = trans[transKey] || trans[elementId] || element.textContent;
  }

  // Update placeholders
  const cropSelect = document.getElementById("cropSelect");
  const stateSelect = document.getElementById("stateSelect");
  const districtSelect = document.getElementById("districtSelect");
  if (cropSelect) cropSelect.querySelector("option[value='']").textContent = trans["cropPlaceholder"] || "Crop";
  if (stateSelect) stateSelect.querySelector("option[value='']").textContent = trans["statePlaceholder"] || "State";
  if (districtSelect) districtSelect.querySelector("option[value='']").textContent = trans["districtPlaceholder"] || "District";
  
  const msgInput = document.getElementById("msgInput");
  if (msgInput) msgInput.placeholder = trans["msgInputPlaceholder"] || "Type your crop concern";
}

window.applyTranslations = applyTranslations;
window.getTranslation = (lang, key) => (TRANSLATIONS[lang] || TRANSLATIONS.English)[key] || key;
